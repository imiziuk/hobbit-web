"""Generate src/ops_gen.h (C++) and ops.js (JS) from ops.def, the single definition of the .d3dr records.
Usage: python gen_ops.py   (run from anywhere; paths are relative to this file)"""
import pathlib, re

HERE = pathlib.Path(__file__).resolve().parent
VALID = set("uidforRPMBsX-")
ops = []
for ln, line in enumerate((HERE / "ops.def").read_text(encoding="utf-8").splitlines(), 1):
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    m = re.fullmatch(r"(\d+)\s+(\w+)::(\w+)\s+(\S+)", line)
    if not m:
        raise SystemExit(f"ops.def:{ln}: cannot parse: {line!r}")
    code, iface, meth, sig = int(m[1]), m[2], m[3], m[4]
    if not set(sig) <= VALID:
        raise SystemExit(f"ops.def:{ln}: bad sig {sig!r}")
    ops.append((code, iface, meth, "" if sig == "-" else sig))
codes = [o[0] for o in ops]
assert len(codes) == len(set(codes)), "duplicate op code"
assert all(c < 256 for c in codes)

h = ["// GENERATED by gen_ops.py from ops.def. Do not edit.", "#pragma once", "",
     "enum Op : unsigned char {"]
for code, iface, meth, sig in ops:
    h.append(f"    OP_{iface}_{meth} = {code},")
h += ["};", "", "// signature of each op (fields after `this`), indexed by code; NULL = unused code",
      "static const char* const OP_SIG[256] = {"]
table = {c: (i, m, s) for c, i, m, s in ops}
for c in range(256):
    if c in table:
        i, m, s = table[c]
        h.append(f'    /*{c:3}*/ "{s}",  // {i}::{m}')
    else:
        h.append(f"    /*{c:3}*/ nullptr,")
h += ["};", ""]
(HERE / "src" / "ops_gen.h").write_text("\n".join(h), encoding="utf-8")

js = ["// GENERATED by gen_ops.py from ops.def. Do not edit.",
      "// OPS[code] = {iface, name, sig}; interface records (code < 192) start with the `this` id.",
      "export const OPS = [];"]
for code, iface, meth, sig in ops:
    js.append(f'OPS[{code}] = {{iface: "{iface}", name: "{meth}", sig: "{sig}"}};')
js += ["export const OP = {};", "OPS.forEach((o, c) => { if (o) OP[o.iface + '_' + o.name] = c; });",
       "export const META_BASE = 192, OP_HR = 240;", ""]
(HERE / "ops.js").write_text("\n".join(js), encoding="utf-8")
print(f"{len(ops)} ops -> src/ops_gen.h, ops.js")
